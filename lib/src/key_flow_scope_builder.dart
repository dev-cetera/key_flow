/// A widget that provides access to the nearest [KeyFlowScope] up the widget
/// tree via its [builder].
class KeyFlowScopeBuilder extends StatelessWidget {
  //
  //
  //

  final ValueWidgetBuilder<KeyFlowScope> builder;
  final Widget? child;

  //
  //
  //

  const KeyFlowScopeBuilder({
    super.key,
    required this.builder,
    this.child,
  });

  //
  //
  //

  @override
  Widget build(BuildContext context) {
    final scope = KeyFlowScope.of(context);
    assert(scope != null);
    if (scope == null) {
      return const SizedBox.shrink();
    }
    return builder(
      context,
      scope,
      child,
    );
  }
}
