/// A [LocalKey] that provides a desciption callback. The callback also
/// provides a [BuildContext] that may be used to access the [Locale] and
/// translate the description dynamically, via something like
/// `Localizations.localeOf(context)` or similar.
abstract class DescriptiveKey extends LocalKey {
  final _KeyDescription description;
  const DescriptiveKey(this.description);
}

// ░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░

typedef _KeyDescription = String Function(BuildContext context);
